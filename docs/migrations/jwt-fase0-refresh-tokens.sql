-- Fase 0 de JWT: familias de refresco y refresh tokens (PostgreSQL 16).
-- Script de referencia, coherente con las entidades FamiliaRefresco y RefreshToken.
-- Desarrollo (ddl-auto=update) y pruebas (ddl-auto=create-drop) crean estas tablas sin este script.
-- Sirve para revisar el esquema y como base de una futura migracion versionada antes del despliegue
-- en Kubernetes. Ejecutar una sola vez, con respaldo previo, sobre una base que ya tenga la tabla usuario.
--
-- Conservacion del estado de revocacion de cada familia (claim sid del token de acceso):
--   * Revocar nunca borra filas: solo fija revocada_en y motivo_revocacion en familia_refresco.
--   * La purga borra los refresh tokens cuyo expira_en ya paso. Las familias solo se borran cuando
--     expira_en + duracion del token de acceso + tolerancia del reloj ya paso, es decir, cuando
--     ningun token de acceso que las referencie puede seguir siendo valido.
--   * Un sid que no existe en familia_refresco se trata como revocado.
--   * El refresh token de una familia nunca debe expirar despues que la propia familia.

BEGIN;

CREATE TABLE IF NOT EXISTS familia_refresco (
    id                uuid                        NOT NULL,
    usuario_id        bigint                      NOT NULL,
    creada_en         timestamp(6) with time zone NOT NULL,
    expira_en         timestamp(6) with time zone NOT NULL,
    revocada_en       timestamp(6) with time zone,
    motivo_revocacion varchar(30),
    CONSTRAINT familia_refresco_pkey PRIMARY KEY (id),
    CONSTRAINT fk_familia_refresco_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT familia_refresco_motivo_revocacion_check
        CHECK (motivo_revocacion IN ('CIERRE_SESION', 'REUTILIZACION_DETECTADA', 'USUARIO_DESACTIVADO'))
);

CREATE INDEX IF NOT EXISTS ix_familia_refresco_usuario ON familia_refresco (usuario_id);
CREATE INDEX IF NOT EXISTS ix_familia_refresco_expira ON familia_refresco (expira_en);

CREATE TABLE IF NOT EXISTS refresh_token (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    familia_id  uuid                        NOT NULL,
    token_hash  varchar(64)                 NOT NULL,
    emitido_en  timestamp(6) with time zone NOT NULL,
    expira_en   timestamp(6) with time zone NOT NULL,
    usado_en    timestamp(6) with time zone,
    CONSTRAINT refresh_token_pkey PRIMARY KEY (id),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_familia FOREIGN KEY (familia_id)
        REFERENCES familia_refresco (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_refresh_token_familia ON refresh_token (familia_id);
CREATE INDEX IF NOT EXISTS ix_refresh_token_expira ON refresh_token (expira_en);

COMMIT;
