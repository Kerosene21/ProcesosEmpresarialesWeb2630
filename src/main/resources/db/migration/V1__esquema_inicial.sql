create index ix_evento_pool on evento (pool_id, activo);
create index ix_evento_pool_destino on evento (pool_destino_id, activo);
create index ix_familia_refresco_usuario on familia_refresco (usuario_id);
create index ix_familia_refresco_expira on familia_refresco (expira_en);
create index ix_gateway_proceso on gateway (proceso_id, activo);
create index ix_gateway_pool on gateway (pool_id, activo);
create index ix_historial_rol_proceso_rol on historial_rol_proceso (rol_proceso_id, fecha);
create index ix_lane_rol_proceso on lane (rol_proceso_id);
create index ix_lane_pool on lane (pool_id, activo, orden);
create index ix_pool_proceso on pool (proceso_id, activo, orden);
create index ix_proceso_compartido_invitada on proceso_compartido_empresa (empresa_invitada_id, activo);
create index ix_refresh_token_familia on refresh_token (familia_id);
create index ix_refresh_token_expira on refresh_token (expira_en);

