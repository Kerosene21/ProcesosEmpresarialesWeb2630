-- Esquema inicial de Procesos Empresariales para PostgreSQL 16.
-- Equivale al DDL que Hibernate 7.4 genera para las entidades JPA actuales: mismos tipos, valores por
-- defecto, restricciones CHECK de las enumeraciones, claves unicas, indices y nombres de llaves foraneas.
-- Conservar los nombres permite que una base existente, una vez comparada y marcada con baseline,
-- quede identica a una base creada desde cero.

create table empresa (
    id bigint generated by default as identity,
    nit varchar(20) not null,
    nombre varchar(150) not null,
    correo_contacto varchar(180) not null,
    primary key (id),
    constraint uk_empresa_nit unique (nit)
);

create table usuario (
    activo boolean not null,
    empresa_id bigint not null,
    id bigint generated by default as identity,
    rol varchar(20) not null check ((rol in ('ADMINISTRADOR','EDITOR','SOLO_LECTURA'))),
    password_hash varchar(100) not null,
    username varchar(180) not null,
    primary key (id),
    constraint uk_usuario_username unique (username)
);

create table proceso (
    eliminado boolean default false not null,
    empresa_id bigint not null,
    id bigint generated by default as identity,
    estado varchar(20) not null check ((estado in ('BORRADOR','PUBLICADO'))),
    categoria varchar(100) not null,
    nombre varchar(150) not null,
    descripcion text not null,
    primary key (id),
    constraint uk_proceso_empresa_nombre unique (empresa_id, nombre)
);

create table pool (
    activo boolean default true not null,
    caja_negra boolean default false not null,
    orden integer default 1 not null,
    empresa_participante_id bigint,
    id bigint generated by default as identity,
    proceso_id bigint not null,
    nombre varchar(150) not null,
    tipo varchar(20) default 'PROPIETARIO' not null check ((tipo in ('PROPIETARIO','PARTICIPANTE','EXTERNO'))),
    primary key (id)
);

create table rol_proceso (
    activo boolean not null,
    empresa_id bigint not null,
    id bigint generated by default as identity,
    nombre varchar(100) not null,
    descripcion varchar(500) not null,
    primary key (id),
    constraint uk_rol_proceso_empresa_nombre unique (empresa_id, nombre)
);

create table lane (
    activo boolean default true not null,
    orden integer default 1 not null,
    id bigint generated by default as identity,
    pool_id bigint not null,
    rol_proceso_id bigint,
    nombre varchar(150),
    primary key (id),
    constraint ck_lane_nombre_o_rol_proceso check (nombre is not null or rol_proceso_id is not null)
);

create table actividad (
    activo boolean not null,
    posicion_x integer not null,
    posicion_y integer not null,
    id bigint generated by default as identity,
    lane_id bigint not null,
    proceso_id bigint not null,
    tipo varchar(20) not null check ((tipo in ('TAREA_USUARIO','TAREA_SISTEMA','TAREA_MANUAL','TAREA_SERVICIO'))),
    nombre varchar(150) not null,
    primary key (id),
    constraint uk_actividad_proceso_nombre unique (proceso_id, nombre)
);

create table gateway (
    activo boolean not null,
    posicion_x integer not null,
    posicion_y integer not null,
    id bigint generated by default as identity,
    pool_id bigint not null,
    proceso_id bigint not null,
    tipo varchar(20) not null check ((tipo in ('EXCLUSIVO','PARALELO','INCLUSIVO'))),
    primary key (id)
);

create table evento (
    activo boolean not null,
    origen_externo boolean,
    posicion_x integer not null,
    posicion_y integer not null,
    id bigint generated by default as identity,
    pool_destino_id bigint,
    pool_id bigint not null,
    proceso_id bigint not null,
    comportamiento_fallo varchar(20) check ((comportamiento_fallo in ('CONTINUAR','RUTA_ERROR','FINALIZAR'))),
    comportamiento_sin_caso varchar(20) check ((comportamiento_sin_caso in ('DESCARTAR','INICIAR_NUEVO_CASO'))),
    tipo varchar(20) not null check ((tipo in ('ENVIO_EXTERNO','MESSAGE_THROW','MESSAGE_CATCH'))),
    tipo_destino varchar(20) check ((tipo_destino in ('CORREO','SERVICIO_WEB','COLA'))),
    variante varchar(20) check ((variante in ('INICIO','INTERMEDIO'))),
    clave_correlacion varchar(100),
    nombre_mensaje varchar(150) not null,
    momento_proceso varchar(300),
    actividades_uso varchar(1000),
    contenido varchar(2000),
    datos_enviados varchar(2000),
    datos_esperados varchar(2000),
    primary key (id)
);

create table arco (
    activo boolean not null,
    destino_id bigint not null,
    id bigint generated by default as identity,
    origen_id bigint not null,
    proceso_id bigint not null,
    destino_tipo varchar(20) not null check ((destino_tipo in ('ACTIVIDAD','GATEWAY','EVENTO'))),
    origen_tipo varchar(20) not null check ((origen_tipo in ('ACTIVIDAD','GATEWAY','EVENTO'))),
    etiqueta varchar(150),
    condicion varchar(200),
    primary key (id)
);

create table historial_proceso (
    fecha timestamp(6) not null,
    id bigint generated by default as identity,
    proceso_id bigint not null,
    usuario_id bigint not null,
    estado_anterior varchar(20) not null,
    cambios_realizados text not null,
    primary key (id)
);

create table historial_rol_proceso (
    fecha timestamp(6) not null,
    id bigint generated by default as identity,
    rol_proceso_id bigint not null,
    usuario_id bigint not null,
    accion varchar(20) not null check ((accion in ('CREACION','EDICION','ELIMINACION'))),
    cambios_realizados text not null,
    primary key (id)
);

create table permiso_estructura_proceso (
    crear_lane boolean not null,
    crear_pool boolean not null,
    editar_lane boolean not null,
    editar_pool boolean not null,
    eliminar_lane boolean not null,
    eliminar_pool boolean not null,
    id bigint generated by default as identity,
    proceso_id bigint not null,
    rol varchar(20) not null check ((rol in ('ADMINISTRADOR','EDITOR','SOLO_LECTURA'))),
    primary key (id),
    constraint uk_permiso_estructura_proceso_rol unique (proceso_id, rol)
);

create table proceso_compartido_empresa (
    activo boolean not null,
    empresa_invitada_id bigint not null,
    id bigint generated by default as identity,
    proceso_id bigint not null,
    primary key (id),
    constraint uk_proceso_compartido_empresa unique (proceso_id, empresa_invitada_id)
);

create table familia_refresco (
    creada_en timestamp(6) with time zone not null,
    expira_en timestamp(6) with time zone not null,
    revocada_en timestamp(6) with time zone,
    usuario_id bigint not null,
    id uuid not null,
    motivo_revocacion varchar(30) check ((motivo_revocacion in ('CIERRE_SESION','REUTILIZACION_DETECTADA','USUARIO_DESACTIVADO'))),
    primary key (id)
);

create table refresh_token (
    emitido_en timestamp(6) with time zone not null,
    expira_en timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    usado_en timestamp(6) with time zone,
    familia_id uuid not null,
    token_hash varchar(64) not null,
    primary key (id),
    constraint uk_refresh_token_hash unique (token_hash)
);

